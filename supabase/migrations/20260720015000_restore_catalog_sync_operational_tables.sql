-- The pre-owner hosted tables used integer variant IDs. Fail closed if any
-- value would be discarded, otherwise perform the lossless type correction
-- recorded and tested in RPagentOS#32.
DO $block$
DECLARE
    target_table text;
    current_type text;
    populated bigint;
BEGIN
    FOREACH target_table IN ARRAY ARRAY['catalog_sync_failures', 'catalog_change_outbox']
    LOOP
        SELECT data_type
          INTO current_type
          FROM information_schema.columns
         WHERE table_schema = 'public'
           AND table_name = target_table
           AND column_name = 'variant_id';

        IF current_type IN ('integer', 'bigint', 'smallint') THEN
            EXECUTE format('SELECT count(*) FROM public.%I WHERE variant_id IS NOT NULL', target_table)
               INTO populated;
            IF populated <> 0 THEN
                RAISE EXCEPTION '% has % non-null legacy variant_id values; refusing lossy UUID conversion',
                    target_table, populated;
            END IF;
            EXECUTE format(
                'ALTER TABLE public.%I ALTER COLUMN variant_id TYPE uuid USING NULL::uuid',
                target_table
            );
        ELSIF current_type <> 'uuid' THEN
            RAISE EXCEPTION '%.variant_id has unsupported type %', target_table, current_type;
        END IF;
    END LOOP;
END
$block$;

DO $block$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'public.catalog_sync_failures'::regclass
           AND conname = 'catalog_sync_failures_variant_id_fkey'
    ) THEN
        ALTER TABLE public.catalog_sync_failures
            ADD CONSTRAINT catalog_sync_failures_variant_id_fkey
            FOREIGN KEY (variant_id) REFERENCES public.product_variants(id) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'public.catalog_change_outbox'::regclass
           AND conname = 'catalog_change_outbox_variant_id_fkey'
    ) THEN
        ALTER TABLE public.catalog_change_outbox
            ADD CONSTRAINT catalog_change_outbox_variant_id_fkey
            FOREIGN KEY (variant_id) REFERENCES public.product_variants(id) ON DELETE SET NULL;
    END IF;
END
$block$;

