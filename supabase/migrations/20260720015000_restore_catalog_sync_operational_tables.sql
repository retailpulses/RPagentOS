-- This migration sorts before 20260720020000, its first canonical dependent
-- migration. It is idempotent for both a clean database and hosted state.

CREATE TABLE IF NOT EXISTS public.catalog_sync_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    status text NOT NULL DEFAULT 'running',
    total_skus integer DEFAULT 0,
    upserted integer DEFAULT 0,
    skipped integer DEFAULT 0,
    not_found integer DEFAULT 0,
    catalog_unavailable integer DEFAULT 0,
    errors integer DEFAULT 0,
    presale_protected integer DEFAULT 0,
    mercari_triggered integer DEFAULT 0,
    price_changed integer DEFAULT 0,
    source_cursor text,
    duration_seconds numeric,
    error_summary text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.catalog_sync_failures (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint REFERENCES public.catalog_sync_runs(id) ON DELETE SET NULL,
    item_code text NOT NULL,
    variant_id uuid REFERENCES public.product_variants(id) ON DELETE SET NULL,
    error_code text,
    error_message text,
    attempt_count integer NOT NULL DEFAULT 1,
    next_retry_at timestamptz,
    status text NOT NULL DEFAULT 'pending',
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_attempt_at timestamptz,
    resolved_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.catalog_change_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type text NOT NULL,
    item_code text NOT NULL,
    variant_id uuid REFERENCES public.product_variants(id) ON DELETE SET NULL,
    dedupe_key text,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text NOT NULL DEFAULT 'pending',
    available_at timestamptz NOT NULL DEFAULT now(),
    claimed_at timestamptz,
    claimed_by text,
    attempt_count integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz,
    last_error text,
    processed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

